#!/usr/bin/env python3
"""Generates tests/c1/dcl_wpm.asm/.exp: the functional side of DCL and WPM (spec 6.3, 6.5; the pins are C2/C6).
System: one 4002 (chip 0) on each of the 4 banks (tb_prog.sv), all read through SRC P0 = 0x00.
 DCL: a write goes to every selected bank and to no other (all 8 codes' lines, spec 6.5); DCL uses acc[2:0] only
      (acc 8, 9, 10, 12 select banks 0, 1, 2, 3); DCL leaves acc unchanged. Reads are done with one bank
      selected only, because a read with several banks selected is undefined (spec 7, Decision C).
 WPM: no effect in our system (spec 6.3): acc, cy, registers and RAM are unchanged."""
import os
d = os.path.dirname(os.path.abspath(__file__))
A = ["; C1: functional DCL and WPM, generated by gen_dcl_wpm.py (see its docstring). WRR/WRM log acc.", "        nop", "        fim p0, 0"]
E = []
def sel(code): A.extend([f"        ldm {code}", "        dcl", "        src p0"])
def wr(code, v): sel(code); A.extend([f"        ldm {v}", "        wrm"]); E.append(v)
def rd(code, expect): sel(code); A.extend(["        rdm", "        wrr"]); E.append(expect)
bank = {0: 1, 1: 2, 2: 3, 3: 4}                 # model of the four characters, from the spec table (6.5)
LINES = {0: [0], 1: [1], 2: [2], 3: [1, 2], 4: [3], 5: [1, 3], 6: [2, 3], 7: [1, 2, 3]}
for code, v in ((0, 1), (1, 2), (2, 3), (4, 4)): wr(code, v)
for code, b in ((0, 0), (1, 1), (2, 2), (4, 3)): rd(code, bank[b])
for code, b in ((8, 0), (9, 1), (10, 2), (12, 3)): rd(code, bank[b])      # DCL uses acc[2:0] only
A.extend(["        ldm 5", "        dcl", "        wrr"]); E.append(5)    # DCL leaves acc unchanged
for code, v in ((3, 9), (5, 6), (6, 7), (7, 8)):
    wr(code, v)
    for b in LINES[code]: bank[b] = v
    for rc, b in ((0, 0), (1, 1), (2, 2), (4, 3)): rd(rc, bank[b])
# WPM: no effect
sel(0)
A.extend(["        ldm 7", "        xch r3", "        ldm 5", "        stc", "        wpm"]); E.append(5)   # X2 drives acc (WPM is an I/O write)
A.extend(["        wrr"]); E.append(5)                                       # acc unchanged
A.extend(["        rdm", "        wrr"]); E.append(bank[0])                 # RAM unchanged (acc was 5, so this is a real read)
A.extend(["        tcc", "        wrr"]); E.append(1)                       # cy unchanged (still 1)
A.extend(["        ld r3", "        wrr"]); E.append(7)                     # register unchanged
A.append("end:    jun end")
open(d + "/dcl_wpm.asm", "w").write("\n".join(A) + "\n")
open(d + "/dcl_wpm.exp", "w").write("\n".join("%X" % e for e in E) + "\n")
print("wrote dcl_wpm:", len(E), "entries")
