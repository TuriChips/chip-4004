#!/usr/bin/env python3
"""Generates the C5 JCN tests (spec 6.2). Expected result computed from the spec equation, not from RTL:
  cond = (C[2] & acc==0) | (C[1] & cy==1) | (C[0] & test==0); jump if cond ^ C[3].
  1. jcn_c<g>_t<test>: every code 0-15 x acc in (0, 5) x cy x test pin (128 cases, 8 programs).
  2. jcn_acc<g>: the acc==0 term alone: codes with C[2] set (4-7, 12-15) x acc in (0, 1, 2, 4, 8, 15),
     cy = 0 and test = 1 so the other two terms are off. A zero test that looked at fewer than four bits
     of acc would fail here (acc 1, 2, 4, 8 each have one bit set, at a different position).
Each case lives in a 16-byte slot, 16 slots per program (one page); WRR logs 2 if the jump was taken, 1 if not."""
import os
d = os.path.dirname(os.path.abspath(__file__))

def expect(C, acc, cy, test):
    cond = ((C >> 2 & 1) and acc == 0) or ((C >> 1 & 1) and cy == 1) or ((C & 1) and test == 0)
    return 2 if bool(cond) != bool(C >> 3 & 1) else 1

def write(name, title, cases, test):
    """cases: list of (C, acc, cy), at most 16."""
    asm = [f"; C5 generated by gen.py: {title}, test pin = {test}. WRR logs 2 = jumped, 1 = not."]; exp = []
    for k, (C, acc, cy) in enumerate(cases):
        last = k == len(cases) - 1
        nxt = 'end' if last else 'n%d' % (k + 1)
        exp.append(expect(C, acc, cy, test))
        asm += [f"        .org {k*16}", f"        ldm {acc}", "        stc" if cy else "        clc",
                f"        jcn {C}, t{k}", "        ldm 1", "        wrr", f"        jun {nxt}",
                f"t{k}:     ldm 2", "        wrr", f"        jun {nxt}"]
        if not last: asm.append(f"        .org {(k+1)*16}\nn{k+1}:")
    asm += ["        .org 252", "end:    jun end"]
    n = f"{d}/{name}"
    open(n + ".asm", "w").write("\n".join(asm) + "\n")
    open(n + ".exp", "w").write("\n".join("%X" % e for e in exp) + "\n")
    open(n + ".plus", "w").write(f"+TEST={test}\n")

for test in (0, 1):
    for g in range(4):
        write(f"jcn_c{g}_t{test}", f"JCN codes {4*g}-{4*g+3}",
              [(C, acc, cy) for C in range(4 * g, 4 * g + 4) for acc in (0, 5) for cy in (0, 1)], test)
sweep = [(C, acc, 0) for C in (4, 5, 6, 7, 12, 13, 14, 15) for acc in (0, 1, 2, 4, 8, 15)]
for g in range(0, len(sweep), 16):
    write(f"jcn_acc{g // 16}", "acc==0 term alone", sweep[g:g + 16], 1)
