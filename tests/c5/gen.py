#!/usr/bin/env python3
"""Generates the C5 JCN tests: every condition code 0-15 x acc==0 or not x cy x test pin (spec 6.2).
Expected result computed from the spec 6.2 equation, not from RTL:
  cond = (C[2] & acc==0) | (C[1] & cy==1) | (C[0] & test==0); jump if cond ^ C[3].
Writes tests/c5/jcn_c<g>_t<test>.asm/.exp/.plus (g = condition group of 4 codes; one 256-byte page each).
Each case lives in a 16-byte slot; WRR logs 2 if the jump was taken, 1 if not."""
import os
d = os.path.dirname(os.path.abspath(__file__))
for test in (0, 1):
    for g in range(4):
        asm = [f"; C5 generated by gen.py: JCN codes {4*g}-{4*g+3}, test pin = {test}. WRR logs 2 = jumped, 1 = not."]
        exp = []; k = 0
        for C in range(4 * g, 4 * g + 4):
            for acc in (0, 5):
                for cy in (0, 1):
                    cond = ((C >> 2 & 1) and acc == 0) or ((C >> 1 & 1) and cy == 1) or ((C & 1) and test == 0)
                    jump = bool(cond) != bool(C >> 3 & 1)
                    exp.append(2 if jump else 1)
                    last = k == 15
                    asm += [f"        .org {k*16}",
                            f"        ldm {acc}", "        stc" if cy else "        clc",
                            f"        jcn {C}, t{k}",
                            "        ldm 1", "        wrr", f"        jun {'end' if last else 'n%d' % (k+1)}",
                            f"t{k}:     ldm 2", "        wrr", f"        jun {'end' if last else 'n%d' % (k+1)}"]
                    if not last: asm.append(f"        .org {(k+1)*16}\nn{k+1}:")
                    k += 1
        asm += ["        .org 252", "end:    jun end"]
        n = f"{d}/jcn_c{g}_t{test}"
        open(n + ".asm", "w").write("\n".join(asm) + "\n")
        open(n + ".exp", "w").write("\n".join("%X" % e for e in exp) + "\n")
        open(n + ".plus", "w").write(f"+TEST={test}\n")
